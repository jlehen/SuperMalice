// ---------------------------------------------------------------------
//  Les "tableaux" (voir tout en haut) : on les pose bout à bout, de gauche à droite, pour faire la carte
//  ("map") du niveau. Les colonnes écrites dans un tableau (updrafts, storms, winds, clairDeLune, arene)
//  sont comptées depuis le bord gauche de ce tableau : on les décale ici.
// ---------------------------------------------------------------------
for (const level of LEVELS) {
  if (!level.tableaux) continue;
  const rows = Math.max(...level.tableaux.map((t) => t.map.length));
  level.map = Array.from({ length: rows }, () => '');
  let col = 0;
  for (const t of level.tableaux) {
    const width = t.map[0].length;
    if (t.map.length !== rows || t.map.some((row) => row.length !== width)) {
      console.error(`levels.js : dans « ${level.name} », le tableau « ${t.nom} » doit avoir ${rows} lignes, toutes de la même longueur.`);
    }
    // (un tableau mal écrit ne casse pas le niveau : on complète avec du vide, en haut et à droite)
    const pad = rows - t.map.length;
    for (let r = 0; r < rows; r++) level.map[r] += (r < pad ? '' : t.map[r - pad]).slice(0, width).padEnd(width, '.');
    for (const key of ['updrafts', 'storms', 'winds']) {
      for (const z of t[key] || []) (level[key] = level[key] || []).push([z[0] + col, z[1] + col, ...z.slice(2)]);
    }
    // (les galeries : seulement dans les colonnes données par les tableaux)
    for (const z of t.galeries || []) (level.galeries = level.galeries || []).push([z[0] + col, z[1] + col]);
    for (const key of ['clairDeLune', 'arene']) {
      if (t[key]) level[key] = [t[key][0] + col, t[key][1] + col];
    }
    col += width;
  }
}

// ---------------------------------------------------------------------
//  Les "etages" (voir tout en haut) : on les empile, du bas vers le haut, pour faire la carte ("map")
//  d'un niveau où l'on grimpe.
// ---------------------------------------------------------------------
for (const level of LEVELS) {
  if (!level.etages) continue;
  const width = level.etages[0].map[0].length;
  level.map = [];
  for (const e of level.etages) {
    if (e.map.some((row) => row.length !== width)) {
      console.error(`levels.js : dans « ${level.name} », l'étage « ${e.nom} » doit avoir des lignes de ${width} cases.`);
    }
    // (un étage mal écrit ne casse pas le niveau : on complète avec du vide, à droite)
    level.map.unshift(...e.map.map((row) => row.slice(0, width).padEnd(width, '.')));
  }
}
