// =====================================================================
//  LES NIVEAUX DE SUPER MALICE
//  Chaque niveau est dessiné avec des lettres : une lettre = une case.
//  Tu peux modifier les cartes ci-dessous pour inventer tes propres niveaux !
//  (Toutes les lignes d'un niveau doivent avoir la même longueur.)
//
//   .  vide                      #  sol
//   B  brique                    -  plateforme qu'on traverse par dessous
//   ~  lave (chocolat au monde des bonbons)   ^  ronces (au sol)     v  ronces (qui pendent)
//   =  pont arc-en-ciel (une plateforme qu'on traverse par dessous)
//   M  champignon qui fait rebondir (guimauve au monde des bonbons)
//      (dans les Champignons Géants, "theme: mushrooms" : chaque rangée de - ou de M côte à côte est un grand
//      chapeau de champignon sur son grand pied ; les M sont les chapeaux bleus à pois qui font rebondir)
//      (avec le badge Super Saut, ↓ gardé en arrivant dessus : Malice s'accroupit sur le chapeau, et saute encore plus haut)
//      (dans le Défi du Super Saut, "theme: sousbois" : - et M sont aussi de grands chapeaux, = est une branche sur un
//      tronc |, et au-dessus du sol, les murs # sont de grosses souches couvertes de mousse)
//      (dans le Marais aux Cabanes, "theme: marsh" : ~ est de la boue où l'on s'enfonce, comme le chocolat ;
//      chaque rangée de 3 - ou plus est le plancher d'une cabane sur pilotis, et = est un pont de corde)
//   w  flaque d'eau, posée sur le sol (plouf ! et Gizmo devient un Gremlin)
//   |  tronc d'arbre (dans le décor : on passe devant ; dans les Grands Arbres, - est une branche)
//   *  pissenlit géant, planté sur une branche ou qui flotte en l'air : on l'attrape en le touchant,
//      et on descend tout doucement avec (↓ pour le lâcher ; il repousse au bout de quelques secondes)
//   _  eau de la rivière (plouf : on ressort sur la berge, tout mouillé, avec un cœur en moins ;
//      la Sirène et le Pingouin nagent dedans)
//   n  nénuphar avec une fleur (solide)        c  nénuphar grignoté : il tremble, puis il coule
//      (les nénuphars se mettent dans la rangée de la surface de l'eau)
//   O  escargot (il laisse de la bave qui glisse)
//   m  taupe (cachée sous l'herbe ; quand Malice passe, elle file sous ses pieds et jaillit du sol)
//   h  hérisson (quand Malice approche, il se met en boule : ça pique ! On lui saute dessus quand il se déroule)
//   s  sanglier (quand il voit Malice, il gratte le sol, puis il fonce tout droit jusqu'à se cogner ou jusqu'au
//      bord : on lui saute dessus pendant qu'il gratte, ou quand il est étourdi ; seul le sanglier qui fonce fait mal)
//   f  grenouille sauteuse (elle adore la pluie ; de temps en temps, elle se ramasse et saute très haut, parfois sur
//      Malice : son ombre montre où elle va retomber. On lui saute dessus quand elle est assise ou ramassée)
//   x  l'axe des ailes d'un moulin à vent : au bout de ses 4 ailes pendent des planches qui restent à plat et nous
//      emportent (elles montent à gauche, passent en haut vers la droite, redescendent à droite). Les planches passent
//      à 3,5 cases de l'axe : tout autour (5 colonnes de chaque côté, de la rangée de l'axe moins 5 jusqu'à plus 4),
//      rien de solide. La tour descend jusqu'au sol (ou jusqu'en bas, dans un trou)
//   a  petit nuage grognon (il flotte au-dessus du sol de son étage, sans jamais le quitter : quand Malice y passe,
//      il la suit, devient tout noir au-dessus d'elle et lui pleut dessus. On saute dedans : pouf, il redevient gentil)
//   z  paratonnerre : une plaque de métal (une plateforme qu'on traverse par dessous), avec sa pointe au milieu (les z
//      côte à côte font un seul paratonnerre). De temps en temps, l'orage l'électrise : ça s'annonce (un petit nuage
//      au-dessus de la pointe, des étincelles, bzz bzz…), puis la plaque grésille : il faut en être descendue avant.
//      Toujours au même rythme ; numérotés de bas en haut, un sur deux est à contretemps (voir LightningRod)
//   >  éboulis : la pente de cailloux de la Grande Glissade (on y glisse sans pouvoir s'arrêter : avec → plus vite,
//      avec ← un peu moins vite). Les > sont les cases où passe la pente, et dessous, de la terre (#) : voir "glissades"
//   0  hérisson de roche : il dort en boule sur la pente. Quand Malice arrive derrière lui, « ! », il dévale la pente en
//      roulant (moins vite qu'elle) : on saute par-dessus, ou on rebondit dessus. Contre un rocher, en bas de la pente,
//      ou écrasé (↓ en l'air), il est tout étourdi, puis il fait la sieste : on lui saute dessus, il redevient gentil
//   +  plaque de glace (solide : on y glisse, on freine mal, et on garde son élan, même en sautant). Là où la glace
//      touche la roche (ou la lave), de la vapeur sort d'une fumerolle (dans le décor). Dans le Glacier Fumant
//      ("theme: glacier"), les stalactites A sont des pointes de glace (elles tremblent plus ou moins longtemps selon
//      la difficulté, puis tombent)
//   1  pingouin grincheux : il se dandine ; quand il voit Malice devant lui, « ! », il plonge sur le ventre et glisse
//      vers elle (très loin sur la glace) : on saute par-dessus. Debout, on lui saute dessus : il redevient gentil
//   J  liane : elle pend du haut de la première case J, aussi longue que les J les uns sous les autres (mettre du
//      bois ou un champignon juste au-dessus). On l'attrape en sautant dessus, on se balance avec ← →, et on saute
//      pour se lancer (tous les personnages)
//   q  écureuil (dans le décor : il grignote un gland devant son trou, et y file quand Malice arrive)
//   k  nid d'oisillons (dans le décor : ils piaillent quand Malice passe)
//   p  le nid secret : un oisillon qui fait un câlin à Malice et lui donne une vie (une seule fois)
//      (dans le Vieux Chêne, "theme: oak" : # est le bois du tronc, et - un champignon-étagère accroché au bois)
//   i  lucioles (un petit groupe qui éclaire la nuit, et qui suit Malice un moment)
//   j  grande fleur-lanterne qui brille (elle éclaire tout autour, la nuit)
//   l  lapin (gentil ; sur l'herbe, il sort la tête de son trou ; dans un terrier, il parle : voir "lapins")
//   L  bloc lutin : 5 bonbons    F  bloc lutin : fruit de la passion
//   K  bloc lutin : caramel      C  bloc lutin : chips au vinaigre
//   S  bloc lutin : étoile (5 bonbons si on n'a pas pris Super Malice)
//   o  bonbon     y  sucette (vaut 5)     b  balle multicolore
//   E  gros oeil à pattes        R  Rubik's cube
//   D  coccinelle                W  coccinelle volante
//   V  chauve-souris (sous le plafond)       A  stalactite qui tombe (sous le plafond)
//   Y  oiseau grincheux          U  ourson en gélatine
//   Q  gros œil bonbon (gentil : si on l'attrape, une vie en plus)
//   g r e t d  minerais (or, rubis, émeraude, topaze, diamant) : ils éclairent la grotte
//   H  plateforme qui va à droite (3 cases)
//   I  plateforme qui monte (3 cases)
//   T  fleur qui parle (ses phrases sont dans "talk", dans l'ordre)
//   @  anneau doré pour la moustache-grappin
//   %  bouchon en chocolat (solide ; seul un éclair au chocolat lancé avec le bocal le fait fondre, avec les % collés
//      au-dessus et en dessous)
//   Z  trophée du badge (fin d'un stage d'entraînement)
//   P  départ de Malice          !  drapeau (on y repart si on perd une vie)
//   G  arrivée du niveau         N  le bébé oiseau (on le sauve dans le volcan)
//   X  la famille du bébé oiseau (fin du jeu)
//   &  le boss du niveau (voir "boss" ; ses pieds sur le sol de la case du dessous)
//
//  "storms" : les colonnes où tombent les éclairs au chocolat [début, fin] (dans un niveau où l'on grimpe :
//             [début, fin, rangée], seulement quand Malice marche sur le sol de cette rangée). Avec une seule
//             colonne ([c, c]), l'éclair tombe toujours au même endroit (un petit nuage qui gronde au-dessus : on se met
//             dessous pour l'attraper avec le bocal, comme dans le Défi du Bocal à éclairs).
//  "winds" : les colonnes où souffle le vent [début, fin, sens] (1 = vers la droite, -1 = vers la gauche).
//  "updrafts" : les colonnes où l'air monte [début, fin, rangée] : avec un pissenlit, on remonte
//             jusqu'à cette rangée (des feuilles s'envolent pour qu'on les voie).
//  "terrier" : à partir de cette rangée, on est sous terre (les galeries d'un terrier secret, avec des racines) :
//             la caméra n'y descend que quand Malice y tombe. Le niveau a alors plus de 13 rangées.
//             Un bloc lutin posé sur un trou qui descend au terrier le cache : on l'écrase pour y entrer.
//  "lapins" : ce que disent les lapins du terrier, dans l'ordre, de gauche à droite.
//  "pluie" : il pleut (des gouttes qui éclaboussent le sol ; les grenouilles sauteuses adorent ça).
//  "dark" : il fait noir (on ne voit qu'autour de Malice et de ce qui brille).
//             "nuit" : c'est la nuit, en plus doux (la lune, les lucioles et les fleurs éclairent).
//  "clairDeLune" : [première colonne, dernière colonne] : la nuit, la lune éclaire ce grand champ
//             (il y fait bien moins noir).
//  "basVisible" : la caméra montre le bas du niveau (la boue sous les ponts du marais : le niveau n'a que
//             12 rangées, presque la hauteur de l'écran) ; elle ne monte que pendant un très haut saut, pour que
//             la tête de Malice reste à l'écran (même au-dessus du haut du niveau : voir World.updateCamera).
//  "haut" : le niveau est bien plus haut que l'écran (on monte dans les grands arbres) : comme pour "grimpe", la caméra
//             suit la branche ou le chapeau où Malice a les pieds, et sa tête ne sort jamais de l'écran (même au-dessus
//             du haut du niveau, après un très grand saut).
//  "cachette" : [première colonne, première rangée, dernière colonne, dernière rangée] : un coin secret caché derrière
//             un gros feuillage (tout en haut d'un arbre) ; les feuilles s'écartent quand Malice entre dedans.
//             (dans les fumerolles du Défi de la Moustache-Grappin, "theme: fumerolles", c'est un gros nuage de vapeur
//             tout en haut, qui s'effiloche quand elle entre ; des braises sautent aussi de la lave)
//  "feuillage" : [[première colonne, première rangée, dernière colonne, dernière rangée], …] : de gros feuillages dans
//             le décor (on passe à travers), par exemple pour accrocher des lianes J sans branche où marcher.
//  "galeries" : les passages bas sous un plafond (une ou deux cases de haut, entre deux cases solides)
//             sont dessinés comme des galeries de terre : une butte se lit comme une colline percée d'un tunnel.
//             true : dans tout le niveau ; ou les colonnes où c'est vrai : [[première, dernière], …].
//  "grimpe" : on monte dans le niveau (bien plus haut que l'écran) : la caméra suit l'étage où Malice a les pieds,
//             et les fleurs qui parlent et les drapeaux vont de bas en haut (un drapeau se touche).
//  "tronc" : [première colonne, dernière colonne] : le tronc creux du Vieux Chêne (ses murs compris). À gauche, c'est
//             dehors (la forêt) : on voit le tronc de l'extérieur, avec sa porte (le trou en bas de son mur de gauche),
//             et dedans, l'écran reste entre ses murs.
//  "couronne" : tout en haut, la rangée (dans le fond) où le tronc s'ouvre sur les feuilles du chêne.
//  "crue" : la rivière déborde (avec "grimpe") : { eau, montees }. Au début, l'eau est en haut de la rangée "eau"
//             (elle remplit tout ce qui est vide en dessous). "montees" : [palier, arrêt, première colonne, dernière
//             colonne, vitesse] : quand Malice monte plus haut que la rangée du palier, entre ces deux colonnes (sur
//             l'escalier), la rivière bouillonne, puis l'eau monte derrière elle, jusqu'en haut de la rangée "arrêt"
//             (juste sous l'étage du dessus), où elle s'arrête. vitesse : 1 = la vitesse de la difficulté (floodSpeed).
//             Les drapeaux sont sur les étages calmes, plus haut que l'arrêt de l'eau d'avant : on y repart avec l'eau
//             arrêtée en dessous. Si Malice tombe dans l'eau, elle redescend (voir floodBack, floodPause dans DIFFS).
//  "phare" : { tour, galerie, rocher } (avec "grimpe") : on grimpe autour d'un phare. tour : [première colonne, dernière
//             colonne] de sa tour, dans le décor (rayée blanc et rouge, du sol jusqu'à sa galerie) ; galerie : la rangée de
//             sa galerie, tout en haut (la lanterne et sa grande lumière qui tourne sont au-dessus) ; rocher : [première
//             colonne, dernière colonne] du rocher à côté du phare : passé le rocher, l'écran reste à sa droite.
//             Sur le sol du départ (P), les drapeaux s'allument comme dans un niveau ordinaire (quand on est passé).
//  "glissades" : les pentes d'éboulis (la Grande Glissade) : [première colonne, rangée du haut, dernière colonne, rangée
//             du bas]. Chacune est une pente toute droite, du coin en haut à gauche de la première case jusqu'au coin en
//             bas à droite de la dernière. Dans la carte : des > dans les cases où passe la pente (ou bien un rocher #,
//             ou un trou, à la place), et de la terre (#) dessous. La caméra suit la pente où Malice glisse : le niveau
//             peut descendre bien plus bas que l'écran.
//  "volcan" : le Bord du Cratère : les colonnes [début, fin] où le volcan gronde (la terre tremble un tout petit peu) et
//             crache des pierres de lave : chacune s'annonce par son ombre par terre, avec un « ! », puis tombe (voir
//             lavaEvery, lavaStones, lavaWarn dans DIFFS) ; [début, fin, n] : il en crache n de plus à chaque fois ;
//             [début, fin, n, k] : et il gronde plus souvent (k fois lavaEvery). Jamais au bord d'un trou ou d'une
//             marche, sur une plateforme qui bouge ou sur une pente, ni pendant qu'une fleur parle ; toujours à l'écran.
//  "glacons" : les stalactites A sont des pointes de glace, comme dans le Glacier Fumant.
//  "nid" : [colonne, rangée] : le grand nid de Maman Aigle (dans le décor), posé sur le sol de cette rangée.
//  "music" : la musique du niveau, si ce n'est pas celle de son monde (voir SONGS dans music.js).
//  "sansBadges" : pour les personnages qui n'ont pas les badges (tous sauf Malice) :
//             "add" : des cases en plus [ligne, colonne, "lettres"] (les anneaux dorés disparaissent),
//             "talk" : d'autres phrases pour les fleurs { numéro de la phrase : "phrase" }.
//
//  LES TABLEAUX
//  Un long niveau peut s'écrire en petits morceaux, les "tableaux", posés bout à bout de gauche à droite :
//  on met "tableaux" à la place de "map". Chaque tableau a son nom ("nom"), son idée, et sa petite carte ("map") :
//  c'est bien plus facile à lire (et à changer !) qu'une seule carte de 600 colonnes. Tous les tableaux d'un
//  niveau ont le même nombre de lignes. Un tableau peut avoir ses "updrafts", "storms", "winds", "galeries",
//  "clairDeLune" et "arene" : leurs colonnes se comptent alors depuis le bord gauche du tableau.
//  Pour ajouter un passage à un niveau, il suffit d'y glisser un tableau de plus.
//  Un tableau peut aussi avoir ses "glissades", son "volcan" et son "nid" : leurs colonnes se comptent de la même
//  façon, depuis son bord gauche.
//  Dans un niveau qui descend ou qui monte (la Grande Glissade, le Bord du Cratère), les tableaux n'ont pas tous la
//  même hauteur, et chacun est posé à sa hauteur : "entree" est la rangée (comptée depuis la première ligne du
//  tableau, qui est la rangée 0) du sol par où l'on y entre, à gauche, et "sortie" celle du sol par où l'on en sort,
//  à droite. Le sol d'entrée d'un tableau se raccorde tout seul au sol de sortie du tableau d'avant. Les rangées
//  écrites dans un tel tableau ("glissades", "updrafts", "nid") se comptent aussi depuis sa première ligne.
//  Au-dessus d'un tableau, la roche (#) et la glace (+) de sa première ligne montent jusqu'en haut du niveau (le
//  reste, c'est du ciel) ; en dessous, la roche, la glace et la lave (~) de sa dernière ligne descendent jusqu'en bas.
//  (outils/franchissable.js vérifie qu'on peut toujours aller jusqu'au bout : voir le README)
//
//  LES ÉTAGES
//  Un niveau où l'on grimpe ("grimpe") peut s'écrire de la même façon, en "etages" empilés les uns sur les autres,
//  du bas vers le haut : le premier de la liste est tout en bas (celui du départ, P), le dernier tout en haut.
//  Chaque étage a son nom ("nom"), son idée, et sa carte ("map"), qui commence par ce qu'il y a de plus haut (comme
//  toutes les cartes) et finit par son plancher : l'étage du dessus se pose juste au-dessus de sa première ligne.
//  Tous les étages d'un niveau ont la même largeur. Les rangées écrites dans un étage se comptent depuis sa première
//  ligne (0 = sa ligne du haut) : "storms" ([début, fin, rangée du sol]), "montees" (les montées de la crue de cet
//  étage, [palier, arrêt, première colonne, dernière colonne, vitesse] : voir "crue") et "eau" (la rangée de l'eau au
//  début, voir "crue" : dans l'étage du bas).
//  Pour rallonger la grimpette, il suffit de glisser un étage de plus dans la pile.
//
//  LES MONDES
//  "world" : le monde du niveau (1 = la Prairie, 2 = la Forêt… voir WORLDS juste en dessous).
//             Dans un monde, les niveaux se suivent dans l'ordre où ils sont écrits ici :
//             le premier est le 1-1, le suivant le 1-2… Pour ajouter un niveau à un monde,
//             il suffit d'écrire un niveau de plus avec son "world" : la carte suit toute seule.
//  "badge" : c'est le stage d'entraînement du monde (une case étoile à côté du chemin, juste
//             avant le monde suivant). Un seul stage par monde.
//  "boss" : le niveau se termine par un boss : son nom (voir js/boss/ : "epouvantail"…) ; il attend sur le "&"
//             de la carte. Sur le dernier niveau d'un monde, sa case devient le château du bout du monde.
//  "arene" : [première colonne, dernière colonne] : l'arène du boss (20 colonnes, la largeur de l'écran).
//             Quand Malice y entre, le boss se réveille et on ne peut plus en sortir tant qu'il n'est pas battu ;
//             l'arrivée (G) n'apparaît qu'après. Mettre un drapeau (!) juste avant : on y repart si on perd une vie.
// =====================================================================

