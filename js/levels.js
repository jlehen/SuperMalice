// ---------------------------------------------------------------------
//  Les "tableaux" (voir tout en haut) : on les pose bout à bout, de gauche à droite, pour faire la carte
//  ("map") du niveau. Les colonnes écrites dans un tableau (updrafts, storms, winds, clairDeLune, arene,
//  glissades, volcan, nid) sont comptées depuis le bord gauche de ce tableau : on les décale ici.
//  Dans un niveau qui monte ou qui descend ("entree" et "sortie"), chaque tableau est aussi posé à sa hauteur,
//  et ses rangées (glissades, updrafts, nid, storms) sont comptées depuis sa première ligne.
// ---------------------------------------------------------------------
for (const level of LEVELS) {
  if (!level.tableaux) continue;
  // "entree", "sortie" : le sol de gauche d'un tableau se raccorde au sol de droite du tableau d'avant
  // (tops : la rangée du niveau où va la première ligne de chaque tableau)
  const stepped = level.tableaux.some((t) => t.entree !== undefined || t.sortie !== undefined);
  const tops = [];
  let top = 0;
  let out = 0;
  level.tableaux.forEach((t, k) => {
    const entree = t.entree || 0;
    if (k > 0) top += out - entree;
    tops.push(top);
    out = t.sortie !== undefined ? t.sortie : entree;
  });
  const first = Math.min(...tops);
  const rows = stepped
    ? Math.max(...level.tableaux.map((t, k) => tops[k] - first + t.map.length))
    : Math.max(...level.tableaux.map((t) => t.map.length));
  level.map = Array.from({ length: rows }, () => '');
  let col = 0;
  level.tableaux.forEach((t, k) => {
    const width = t.map[0].length;
    if ((!stepped && t.map.length !== rows) || t.map.some((row) => row.length !== width)) {
      console.error(`levels.js : dans « ${level.name} », le tableau « ${t.nom} » doit avoir ${stepped ? 'des' : rows} lignes${stepped ? '' : ','} toutes de la même longueur.`);
    }
    // (un tableau mal écrit ne casse pas le niveau : on complète avec du vide, en haut et à droite)
    const pad = stepped ? tops[k] - first : rows - t.map.length;
    const last = t.map.length - 1;
    for (let r = 0; r < rows; r++) {
      let line;
      if (r >= pad && r - pad <= last) line = t.map[r - pad].slice(0, width).padEnd(width, '.');
      // (au-dessus d'un tableau moins haut que le niveau : la roche et la glace de sa première ligne montent
      // jusqu'en haut ; en dessous : la roche, la glace et la lave de sa dernière ligne descendent jusqu'en bas)
      else if (!stepped) line = '.'.repeat(width);
      else if (r < pad) line = t.map[0].slice(0, width).padEnd(width, '.').replace(/[^#+]/g, '.');
      else line = t.map[last].slice(0, width).padEnd(width, '.').replace(/[^#+~]/g, '.');
      level.map[r] += line;
    }
    // (les rangées écrites dans un tableau : à partir de sa première ligne)
    const dr = stepped ? pad : 0;
    for (const key of ['updrafts', 'storms', 'winds', 'volcan']) {
      for (const z of t[key] || []) {
        const rest = z.slice(2);
        if (rest.length && (key === 'updrafts' || key === 'storms')) rest[0] += dr;
        (level[key] = level[key] || []).push([z[0] + col, z[1] + col, ...rest]);
      }
    }
    for (const z of t.glissades || []) (level.glissades = level.glissades || []).push([z[0] + col, z[1] + dr, z[2] + col, z[3] + dr]);
    if (t.nid) level.nid = [t.nid[0] + col, t.nid[1] + dr];
    // (les galeries : seulement dans les colonnes données par les tableaux)
    for (const z of t.galeries || []) (level.galeries = level.galeries || []).push([z[0] + col, z[1] + col]);
    for (const key of ['clairDeLune', 'arene']) {
      if (t[key]) level[key] = [t[key][0] + col, t[key][1] + col];
    }
    col += width;
  });
}

// ---------------------------------------------------------------------
//  Les "etages" (voir tout en haut) : on les empile, du bas (le premier) vers le haut (le dernier), pour faire la
//  carte ("map") d'un niveau où l'on grimpe. Les rangées écrites dans un étage (storms, montees, eau)
//  sont comptées depuis sa première ligne : on les décale ici.
// ---------------------------------------------------------------------
for (const level of LEVELS) {
  if (!level.etages) continue;
  const width = Math.max(...level.etages.map((e) => e.map[0].length));
  const rows = level.etages.reduce((n, e) => n + e.map.length, 0);
  level.map = [];
  let bottom = rows;
  for (const e of level.etages) {
    if (e.map.some((row) => row.length !== width)) {
      console.error(`levels.js : dans « ${level.name} », l'étage « ${e.nom} » doit avoir toutes ses lignes de ${width} colonnes.`);
    }
    // (la rangée de sa première ligne, dans la carte entière)
    const top = bottom - e.map.length;
    level.map.unshift(...e.map.map((row) => row.slice(0, width).padEnd(width, '.')));
    for (const z of e.storms || []) (level.storms = level.storms || []).push([z[0], z[1], z[2] + top]);
    if (e.montees || e.eau !== undefined) {
      level.crue = level.crue || { montees: [] };
      if (e.eau !== undefined) level.crue.eau = e.eau + top;
      for (const m of e.montees || []) level.crue.montees.push([m[0] + top, m[1] + top, ...m.slice(2)]);
    }
    bottom = top;
  }
}
